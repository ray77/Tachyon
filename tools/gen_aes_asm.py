#!/usr/bin/env python3
"""Generate crypto/m68k/aes.s: AES block encryption/decryption with T-tables and
GHASH (GF(2^128) multiply) with Shoup 8-bit tables, for a plain 68000.

Calling convention (vbcc __reg): callee saves d2-d7/a2-a6.
  _aes_enc_block(a0 = round keys (16 bytes each), a1 = in, a2 = out, d0 = rounds)
  _aes_dec_block(a0 = inverse round keys (reversed, InvMixColumns applied), a1, a2, d0)
  _ghash_mul_tab(a0 = y[16] (in/out: y = (y ^ x) * H), a1 = x[16], a2 = ghash_tab)
ghash_tab layout: m[256][4] at 0, m8[256][4] at 4096, rhi[256] at 8192, rlo[256] at 9216.
"""
import sys

def xtime(x): return ((x << 1) ^ (0x1b if x & 0x80 else 0)) & 0xff
def gmul(a, b):
    r = 0
    while b:
        if b & 1: r ^= a
        a = xtime(a); b >>= 1
    return r

# S-box from the field inverse and affine map
sbox = [0] * 256
p = q = 1
while True:
    p = p ^ ((p << 1) & 0xff) ^ (0x1b if p & 0x80 else 0)
    q ^= q << 1; q ^= q << 2; q ^= q << 4; q &= 0xff
    if q & 0x80: q ^= 0x09
    rotl = lambda v, n: ((v << n) | (v >> (8 - n))) & 0xff
    x = q ^ rotl(q, 1) ^ rotl(q, 2) ^ rotl(q, 3) ^ rotl(q, 4)
    sbox[p] = (x ^ 0x63) & 0xff
    if p == 1: break
sbox[0] = 0x63
isbox = [0] * 256
for i, s in enumerate(sbox): isbox[s] = i
assert sbox[0] == 0x63 and sbox[1] == 0x7c and sbox[0x53] == 0xed and sbox[0xff] == 0x16

def word(b0, b1, b2, b3): return (b0 << 24) | (b1 << 16) | (b2 << 8) | b3

def te(k):
    t = []
    for x in range(256):
        s = sbox[x]; col = [gmul(s, 2), s, s, gmul(s, 3)]
        col = col[-k:] + col[:-k]          # rotate rows down by k
        t.append(word(*col))
    return t

def td(k):
    t = []
    for x in range(256):
        s = isbox[x]; col = [gmul(s, 14), gmul(s, 9), gmul(s, 13), gmul(s, 11)]
        col = col[-k:] + col[:-k]
        t.append(word(*col))
    return t

out = []
def e(s=''): out.append(s)

def table(name, vals, size):
    e(f'{name}:')
    for i in range(0, len(vals), 8):
        chunk = vals[i:i + 8]
        if size == 4: e('\tdc.l\t' + ','.join('$%08x' % v for v in chunk))
        else:         e('\tdc.b\t' + ','.join('$%02x' % v for v in chunk))

e('; generated by tools/gen_aes_asm.py - do not edit')
e('\tsection\ttext,code')
e('\tcnop\t0,4')
for k in range(4): table(f'aes_te{k}', te(k), 4)
for k in range(4): table(f'aes_td{k}', td(k), 4)
table('aes_sbox', sbox, 1)
table('aes_isbox', isbox, 1)
e()

def block2(name, tables, sboxname, sign):
    e(f'\txdef\t{name}')
    e(f'{name}:')
    e('\tmovem.l\td2-d7/a2-a6,-(sp)')
    e('\tmove.l\ta2,-(sp)')                 # out pointer at 0(sp) after buffer alloc -> 16(sp)
    e('\tlea\t-16(sp),sp')
    e('\tmove.l\tsp,a6')
    e('\tmove.w\td0,d6')
    e('\tsubq.w\t#2,d6')
    # state = in ^ rk[0]; the input is copied bytewise (in may be odd-aligned)
    for i in range(16): e(f'\tmove.b\t(a1)+,{i}(a6)')
    for c in range(4):
        e(f'\tmove.l\t(a0)+,d{c}')
        e(f'\teor.l\td{c},{4*c}(a6)')
    for k in range(4): e(f'\tlea\t{tables[k]}(pc),a{k+1}')
    e(f'{name}_round:')
    for c in range(4):
        for r in range(4):
            src = 4 * ((c + sign * r) & 3) + r
            e('\tmoveq\t#0,d4')
            e(f'\tmove.b\t{src}(a6),d4')
            e('\tadd.w\td4,d4')
            e('\tadd.w\td4,d4')
            if r == 0: e(f'\tmove.l\t(a{r+1},d4.w),d{c}')
            else:
                e(f'\tmove.l\t(a{r+1},d4.w),d5')
                e(f'\teor.l\td5,d{c}')
        e('\tmove.l\t(a0)+,d5')
        e(f'\teor.l\td5,d{c}')
    e('\tmovem.l\td0-d3,(a6)')
    e(f'\tdbf\td6,{name}_round')
    # final round: SubBytes + ShiftRows + AddRoundKey, written to out
    # final round into registers d0-d3 (SubBytes/ShiftRows via S-box, AddRoundKey), then bytewise out
    e(f'\tlea\t{sboxname}(pc),a1')
    e('\tmove.l\t16(sp),a2')
    e('\tmoveq\t#0,d4')
    for c in range(4):
        for r in range(4):
            src = 4 * ((c + sign * r) & 3) + r
            e(f'\tmove.b\t{src}(a6),d4')
            if r == 0:
                e(f'\tmove.b\t(a1,d4.w),d{c}')
            else:
                e(f'\tlsl.l\t#8,d{c}')
                e(f'\tmove.b\t(a1,d4.w),d{c}')
        e('\tmove.l\t(a0)+,d5')
        e(f'\teor.l\td5,d{c}')
    e('\tmovem.l\td0-d3,(a6)')
    for i in range(16): e(f'\tmove.b\t{i}(a6),(a2)+')
    e('\tlea\t20(sp),sp')
    e('\tmovem.l\t(sp)+,d2-d7/a2-a6')
    e('\trts')
    e()

block2('_aes_enc_block', ['aes_te0', 'aes_te1', 'aes_te2', 'aes_te3'], 'aes_sbox', +1)
block2('_aes_dec_block', ['aes_td0', 'aes_td1', 'aes_td2', 'aes_td3'], 'aes_isbox', -1)

# GHASH: y = (y ^ x) * H with 8-bit Shoup tables, two bytes per step
e('\txdef\t_ghash_mul_tab')
e('_ghash_mul_tab:')
e('\tmovem.l\td2-d7/a2-a6,-(sp)')
e('\tlea\t-16(sp),sp')
e('\tmove.l\tsp,a6')
for i in range(16): e(f'\tmove.b\t(a1)+,{i}(a6)')
for c in range(4):
    e(f'\tmove.l\t(a0)+,d{c}')
    e(f'\teor.l\td{c},{4*c}(a6)')
e('\tlea\t-16(a0),a0')
e('\tlea\t4096(a2),a3')          # m8
e('\tlea\t8192(a2),a4')          # rhi
e('\tlea\t9216(a2),a5')          # rlo
def lookup(byteoff, tabreg, first):
    e('\tmoveq\t#0,d4')
    e(f'\tmove.b\t{byteoff}(a6),d4')
    e('\tlsl.w\t#4,d4')
    for c in range(4):
        if first:
            e(f'\tmove.l\t{4*c}({tabreg},d4.w),d{c}')
        else:
            e(f'\tmove.l\t{4*c}({tabreg},d4.w),d5')
            e(f'\teor.l\td5,d{c}')
lookup(14, 'a2', True)
lookup(15, 'a3', False)
for i in range(12, -1, -2):
    # Z = Z * x^16: reduction of bytes 14 (d3 bits 8-15) and 15 (d3 low byte)
    e('\tmoveq\t#0,d4')
    e('\tmove.b\td3,d4')
    e('\tadd.w\td4,d4')
    e('\tadd.w\td4,d4')
    e('\tmove.l\t(a5,d4.w),d5')          # rlo[z15]
    e('\tmove.w\td3,d4')
    e('\tlsr.w\t#6,d4')
    e('\tand.w\t#$3fc,d4')
    e('\tmove.l\t(a4,d4.w),d4')          # rhi[z14]
    e('\teor.l\td4,d5')
    # new d3 = L2:H3 etc.: put the low word of the next-higher register into the low word, then swap
    e('\tmove.w\td2,d3')
    e('\tswap\td3')
    e('\tmove.w\td1,d2')
    e('\tswap\td2')
    e('\tmove.w\td0,d1')
    e('\tswap\td1')
    e('\tclr.w\td0')
    e('\tswap\td0')
    e('\teor.l\td5,d0')
    lookup(i, 'a2', False)
    lookup(i + 1, 'a3', False)
e('\tmovem.l\td0-d3,(a0)')
e('\tlea\t16(sp),sp')
e('\tmovem.l\t(sp)+,d2-d7/a2-a6')
e('\trts')
sys.stdout.write('\n'.join(out) + '\n')
