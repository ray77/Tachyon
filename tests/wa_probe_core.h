/*
 * Tachyon - the WhatsApp connection probe, transport agnostic.
 *
 * TCP -> TLS 1.3 (tls13.c, pins {DigiCert G2 root, G2 TLS RSA 2020 CA1 intermediate} from
 * tests/certs/wa_rsa_chain.h, optional certificate cache) -> WebSocket upgrade (ws.c) -> Noise XX
 * ClientHello / ServerHello / ClientFinish (noise.c, WhatsApp's certificate chain checked with XEdDSA
 * against the WA root key) with the pong heartbeat armed during `gap_ms` of X25519 ladders, then the
 * first encrypted server frame is decrypted. The caller supplies the socket (send / recv with timeout /
 * reconnect), a millisecond clock, a line logger, the DRBG seed and the clock string; the same code runs
 * on the host (tests/wa_probe.c, POSIX) and on the Amiga (bench/wa_probe_amiga.c, bsdsocket.library).
 * No libc: freestanding like crypto/ref (own copy/compare/format helpers).
 *
 * Two steps: wa_probe_prepare does everything that needs no connection - DRBG, the TLS 1.3 X25519 key pair and
 * the two Noise X25519 key pairs (static + ephemeral, fixed-base comb) - so the caller can run it before the TCP
 * connect (on the A500 ~10 s, while the stack is still starting); wa_probe_run then takes the open socket.
 * WhatsApp's intermediate Noise certificate is verified once and remembered as a fingerprint
 * (noise_cert_cache, noise.h): the caller may pass a stored fingerprint in and gets the current one out.
 */
#ifndef TACHYON_WA_PROBE_CORE_H
#define TACHYON_WA_PROBE_CORE_H

#include <stdint.h>
#include "tls13.h"
#include "qr.h"

struct wa_creds; struct wa_prekeys; struct wa_nextkeys; struct sig_store;

/* io->mode */
#define WA_MODE_PROBE 0     /* the connection probe: handshake, first frame decrypted, close (unchanged behaviour) */
#define WA_MODE_PAIR  1     /* companion pairing / login (docs/PROTOCOL.md 11): creds without a JID -> QR pairing, then the
                               515 restart and the login connection; creds with a JID -> login only. Done = <success>. */
#define WA_QR_REFS_MAX 8

#define WA_PROBE_MSG_MAX 16384      /* reassembled WebSocket message / decrypted frame (handshake frames are < 1 KiB) */

typedef struct wa_probe_io {
    void *ctx;
    int      (*send)(void *ctx, const uint8_t *p, uint32_t n);                     /* 1 = all bytes on the wire */
    int32_t  (*recv)(void *ctx, uint8_t *p, uint32_t cap, uint32_t timeout_ms);   /* >0 bytes, 0 timeout, -1 closed */
    void    *(*alloc)(void *ctx, uint32_t n);                                       /* WA_PROBE_ALLOC builds: the big receive buffers (A500: Chip RAM) */
    int      (*reconnect)(void *ctx);           /* new TCP connection to the same server (use_cache only; may be 0) */
    uint32_t (*now_ms)(void);                    /* monotonic milliseconds (the heartbeat takes it without ctx) */
    void     (*log)(void *ctx, const char *line);

    const char *host;           /* "web.whatsapp.com" */
    const char *now;            /* "YYYYMMDDHHMMSSZ" for the certificate validity check, or 0 (no clock) */
    const uint8_t *seed; uint32_t seed_len;     /* DRBG seed: at least 32 bytes of real entropy */
    uint32_t gap_ms;            /* X25519 ladders between ServerHello and ClientFinish (the A500's computing time) */
    uint32_t hold_ms;           /* TLS_HOLD: delay our Finished and watch for the server closing; 0 = off */
    int tunnel;                 /* the transport already is TLS (openssl s_client): skip tls13 */
    int use_cache;              /* prime the certificate cache on a first connection, the real one must hit it */
    int debug;                  /* dump reads and messages */
    const uint8_t *noise_cache_in;  /* 32-byte fingerprint of the verified Noise intermediate from an earlier run, or 0 */
    const uint8_t *noise_leaf_cache_in;     /* 32-byte fingerprint of the verified Noise leaf (under that intermediate), or 0 */
    const uint8_t *tls_cache_in; uint32_t tls_cache_in_len;   /* x509_cache file (x509_cache_write) from an earlier run, or 0 */
    const uint8_t *noise_static_in;         /* WhatsApp's 32-byte Noise static key (== verified leaf key) from an earlier run, or 0:
                                               es = DH(ephemeral, static) is then computed before the connection (noise_es_pre) */

    /* pairing / login (WA_MODE_PAIR) */
    int mode;
    struct wa_creds *creds;     /* in/out: the identity (generated by wa_probe_prepare when creds_loaded is 0), after
                                   pairing JID, ADV identity, platform; the caller persists the record */
    int creds_loaded;           /* 1 = creds hold a stored identity (paired or not) */
    uint32_t qr_mask;           /* QR_MASK_AUTO, or a fixed mask 0..7 (saves ~2 s per code on the 68000) */
    void (*show_qr)(void *ctx, const char *text, const qr *code, uint32_t valid_ms, uint32_t index, uint32_t count);
    void (*qr_tick)(void *ctx, uint32_t remaining_ms);   /* optional: about once a second while a code is shown */
    void (*qr_hide)(void *ctx, const char *status);      /* optional: the code is gone; status text for the display */
    void (*save_creds)(void *ctx);                       /* optional: creds changed, persist them now (before the 515 restart) */
    uint32_t qr_first_ms, qr_next_ms;                    /* validity per code: 0 = whatsmeow's 60 s / 20 s */

    /* after <success> (WA_MODE_PAIR), what whatsmeow's handleConnectSuccess does: prekey count query, upload of the
       pending batch when the server holds fewer than 5, <active/>, then linger_ms online acknowledging receipts and
       notifications (compressed frames inflated) before the close */
    struct wa_prekeys *prekeys;     /* in/out, or 0 = no prekey handling; post_login refills the batch up to prekeys_wanted
                                       pending keys in idle time after <active/> (3.3 s each on the 68000), never before
                                       the connection; runs out -> generated online before the upload */
    int prekeys_loaded;             /* 1 = *prekeys holds a stored record (else it is initialised) */
    uint32_t prekeys_wanted;        /* pending batch size (whatsmeow 50; the A500 takes 10) */
    void (*save_prekeys)(void *ctx);                     /* optional: the batch changed (generated / uploaded) */
    uint32_t linger_ms;             /* how long to stay online after <active/> (0 = close right away) */

    /* key material for the next connection (proto/nextkeys.h): a stored record is consumed at the start - the
       caller's consume_nextkeys deletes it BEFORE the keys are used, single use - and after <active/>, while online,
       the record for the next start is computed (3 comb multiplications + the es ladder, ~15 s on the 68000, off the
       server's clock) and handed back through save_nextkeys */
    struct wa_nextkeys *nextkeys;   /* in/out, or 0 = off */
    int nextkeys_loaded;            /* 1 = *nextkeys holds a stored record for this connection */
    int precompute_next;            /* 1 = compute the next record after <active/> */
    void (*consume_nextkeys)(void *ctx);                 /* the stored record is about to be used: delete the file */
    void (*save_nextkeys)(void *ctx);                    /* *nextkeys holds the record for the next start: persist it */

    /* messages (docs/SIGNAL.md): Signal sessions and the interim chat. With `sessions` set, incoming <message> stanzas
       are decrypted (pkmsg: X3DH as responder with the stored prekeys), printed, acknowledged with a <receipt> as
       whatsmeow does, and the store is handed back through save_sessions after every change; text lines from
       chat_input (and chat_send once, right after <active/>) are encrypted for chat_user:chat_device (a new session
       fetches the prekey bundle first: ~50 s on the 68000) and sent as <message><participants><to><enc>. */
    struct sig_store *sessions;     /* in/out, or 0 = messages are only counted (left unacknowledged) */
    int sessions_loaded;            /* 1 = *sessions holds a stored record (else it is initialised) */
    void (*save_sessions)(void *ctx);
    const char *chat_user; uint32_t chat_device; int chat_lid;   /* the peer: JID user (digits), device (the phone is 0), @lid? */
    const char *chat_send;          /* text to send once after <active/>, or 0 */
    int (*chat_input)(void *ctx, char *line, uint32_t cap);      /* optional: 1 = a typed line is ready (no newline) */
    void (*chat_recv)(void *ctx, const char *from, const char *text);   /* optional: a decrypted text (also logged) */
    uint32_t msgs_sent, msgs_received, msgs_failed, msgs_deferred, receipts_sent, sessions_started;
    uint32_t d_session, d_encrypt, d_decrypt;   /* durations: last X3DH, last encrypt, last decrypt */
    uint32_t t_msg_sent, t_msg_ack, t_msg_receipt, t_msg_received;   /* our last message out, the server's ack, the peer's receipt; the last text in */

    /* pairing results, milliseconds since wa_probe_run started unless noted (0 = not reached) */
    int paired_now;             /* pairing completed in this run (pair-device-sign sent) */
    int logged_in;              /* <success> received on the login connection */
    uint32_t t_qr_shown, t_pair_success, d_verify, d_sign, t_sign_sent, t_515, t_login_connect, t_login_accepted;
    uint32_t qr_shown;          /* codes shown */
    /* post-login results */
    uint32_t d_prekeys;                     /* prekey generation time in this run (online, idle phase) */
    uint32_t server_prekeys, prekeys_uploaded, t_active, frames_after_login, acks_sent, messages_seen;
    int have_server_prekeys, active_set;

    /* results, milliseconds since wa_probe_run started (0 = not reached) */
    uint32_t t_tls, t_ws, t_hello, t_finish, t_accepted;
    uint32_t t_tls_key, t_noise_keys;   /* durations of the key pair computations in wa_probe_prepare */
    uint32_t pongs, ladders;
    int noise_cert_cached;              /* 1 = the intermediate's XEdDSA verification was skipped on a cache hit */
    uint8_t noise_cache_fp[32]; int noise_cache_valid;   /* the fingerprint after the run (store it for the next one) */
    uint8_t noise_leaf_fp[32]; int noise_leaf_valid, noise_leaf_cached;   /* same for the leaf certificate */
    uint8_t noise_static_out[32]; int noise_static_valid;   /* the server static after a verified handshake (store it with the fingerprints) */
    int noise_es_precomputed;           /* 1 = the login/probe connection used the es computed before the connection */
    uint32_t t_es_pre;                  /* duration of that precomputation (0 = none) */
    int nextkeys_used;                  /* 1 = this run's first connection took its key pairs (and es) from the stored record */
    int nextkeys_ready; uint32_t t_nextkeys;   /* the record for the next start was computed (in t_nextkeys ms) */
    uint8_t tls_cache_out[X509_CACHE_FILE_MAX]; uint32_t tls_cache_out_len; int tls_cert_cached;   /* TLS cache after the run */
    uint32_t tls_tickets;               /* NewSessionTicket messages the server sent (PSK resumption not implemented) */
    char result[200];           /* "RESULT: ..." */
} wa_probe_io;

int wa_probe_prepare(wa_probe_io *io); /* offline part: DRBG + 3 X25519 key pairs; 0 = io->result tells why */
int wa_probe_run(wa_probe_io *io);     /* 1 = handshake ACCEPTED by the server; io->result tells the rest
                                          (calls wa_probe_prepare itself if the caller did not) */
tls13 *wa_probe_tls(void);             /* the TLS state (diagnostics after a failure) */

/* tiny formatter shared with the glue code: %s %u %d %x %c %% with optional 0-flag and width, %T = uint32_t
 * milliseconds as "s.cc". Always NUL-terminates; returns the length written. */
uint32_t wa_fmt(char *dst, uint32_t cap, const char *fmt, ...);

#endif
