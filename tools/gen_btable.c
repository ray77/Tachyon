/*
 * Generates crypto/ref/ed25519_btable.h: the odd multiples B, 3B, ..., 63B of the
 * Ed25519 base point as affine "Niels" triples (y+x, y-x, 2dxy), canonical
 * little-endian bytes. Used by the w = 7 fixed-base part of the double scalar
 * multiplication in ed25519.c.
 *
 *   cc -Icrypto/ref tools/gen_btable.c crypto/ref/x25519_ref.c crypto/ref/sha512.c crypto/ref/ed25519.c -o build/gen_btable
 *   build/gen_btable > crypto/ref/ed25519_btable.h
 */
#include <stdio.h>
#include "x25519.h"
#include "ed25519.h"

static void print_fe(const char *name, const fe16 f)
{
    uint8_t b[32];
    int i;
    fe16_tobytes(b, f);
    if (name[0]) printf("      /* %s */ {", name); else printf("{");
    for (i = 0; i < 32; i++) printf("%s0x%02x", i ? "," : "", b[i]);
    printf("}");
}

/* comb table for constant-time fixed-base multiplication: entry [j][d-1] = d * 2^(4j) * B,
 * j = 0..63, d = 1..8, as affine Niels triples */
static void gen_comb(const uint8_t d_bytes[32])
{
    int j, d;
    printf("/* GENERATED by tools/gen_btable.c comb - do not edit. COMB_TABLE[j][d-1] = d * 2^(4j) * B,\n"
           " * j = 0..63, d = 1..8, affine Niels triples { y+x, y-x, 2dxy }, canonical little-endian bytes. */\n");
    printf("static const uint8_t COMB_TABLE[64][8][3][32] = {\n");
    for (j = 0; j < 64; j++) {
        printf("  { /* window %d */\n", j);
        for (d = 1; d <= 8; d++) {
            uint8_t scalar[33] = { 0 };
            ge_p3 P;
            fe16 zinv, x, y, ypx, ymx, xy2d, d2;
            int bit = 4 * j, byte = bit >> 3, shift = bit & 7;
            scalar[byte] |= (uint8_t)(d << shift);
            scalar[byte + 1] |= (uint8_t)((d << shift) >> 8);
            if (j == 63 && d == 8) {
                /* 8 * 2^252 = 2^255: beyond 255 bits, compute as 2^255 B via doubling of 2^254 B */
                uint8_t s2[32] = { 0 };
                s2[31] = 0x40;
                ge_scalarmult_base(&P, s2);
                ge_dbl(&P, &P);
            } else {
                ge_scalarmult_base(&P, scalar);
            }
            fe16_invert(zinv, P.Z);
            fe16_mul(x, P.X, zinv);
            fe16_mul(y, P.Y, zinv);
            fe16_add(ypx, y, x);
            fe16_sub(ymx, y, x);
            fe16_frombytes(d2, d_bytes);
            fe16_add(d2, d2, d2);
            fe16_mul(xy2d, x, y);
            fe16_mul(xy2d, xy2d, d2);
            printf("    {");
            print_fe("", ypx); printf(",");
            print_fe("", ymx); printf(",");
            print_fe("", xy2d); printf("}%s\n", d < 8 ? "," : "");
        }
        printf("  }%s\n", j < 63 ? "," : "");
    }
    printf("};\n");
}

int main(int argc, char **argv)
{
    static const uint8_t d_bytes[32] = {
        0xa3,0x78,0x59,0x13,0xca,0x4d,0xeb,0x75,0xab,0xd8,0x41,0x41,0x4d,0x0a,0x70,0x00,
        0x98,0xe8,0x79,0x77,0x79,0x40,0xc7,0x8c,0x73,0xfe,0x6f,0x2b,0xee,0x6c,0x03,0x52 };
    int k;
    if (argc > 1 && argv[1][0] == 'c') { gen_comb(d_bytes); return 0; }
    printf("/* GENERATED by tools/gen_btable.c - do not edit. Odd multiples (2k+1)B, k = 0..31,\n"
           " * as affine Niels triples { y+x, y-x, 2dxy }, canonical little-endian bytes. */\n");
    printf("static const uint8_t B_TABLE[32][3][32] = {\n");
    for (k = 0; k < 32; k++) {
        uint8_t scalar[32] = { 0 };
        ge_p3 P;
        fe16 zinv, x, y, ypx, ymx, xy2d, d2;
        scalar[0] = (uint8_t)(2 * k + 1);
        ge_scalarmult_base(&P, scalar);
        fe16_invert(zinv, P.Z);
        fe16_mul(x, P.X, zinv);
        fe16_mul(y, P.Y, zinv);
        fe16_add(ypx, y, x);
        fe16_sub(ymx, y, x);
        fe16_frombytes(d2, d_bytes);
        fe16_add(d2, d2, d2);
        fe16_mul(xy2d, x, y);
        fe16_mul(xy2d, xy2d, d2);
        printf("    { /* %dB */\n", 2 * k + 1);
        print_fe("y+x ", ypx); printf(",\n");
        print_fe("y-x ", ymx); printf(",\n");
        print_fe("2dxy", xy2d); printf("\n    }%s\n", k < 31 ? "," : "");
    }
    printf("};\n");
    return 0;
}
