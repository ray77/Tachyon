#!/usr/bin/env python3
"""Generate crypto/m68k/sha256.s: the SHA-256 compression function for the 68000.

    python3 tools/gen_sha256_asm.py > crypto/m68k/sha256.s

  _sha256_block   a0 = uint32_t h[8] (updated in place), a1 = 64-byte block (big-endian)

Fully unrolled. State: a..f in d2..d7, g in a2, h in a3 (g and h are only read
once per round, so address registers are cheap homes for them). d0/d1 are
temporaries, T1 is parked in a5. The 64-word message schedule lives on the
stack; the 68000 is big-endian, so the block is loaded with plain move.l.
Rotations use the cheapest 68000 form: ROTR n for n > 16 becomes swap + a short
rotate, ROTR 25 = ROL 7, ROTR 22 = swap + ROR 6, etc.
"""
import sys

K = [
    0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,
    0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,
    0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,
    0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,
    0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,
    0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,
    0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,
    0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2]

out = []
emit = out.append


def rotr(reg, n):
    """rotate reg right by n (mod 32) with the cheapest 68000 sequence"""
    n %= 32
    if n == 0:
        return
    if n == 16:
        emit(f"\tswap\t{reg}")
    elif n <= 8:
        emit(f"\tror.l\t#{n},{reg}")
    elif n >= 24:
        emit(f"\trol.l\t#{32 - n},{reg}")
    elif n < 16:
        emit(f"\tswap\t{reg}")
        emit(f"\trol.l\t#{16 - n},{reg}")       # ROTR n = ROTR 16 then ROTL (16-n)
    else:
        emit(f"\tswap\t{reg}")
        emit(f"\tror.l\t#{n - 16},{reg}")


def shr(reg, n):
    if n <= 8:
        emit(f"\tlsr.l\t#{n},{reg}")
    else:
        emit(f"\tlsr.l\t#8,{reg}")
        emit(f"\tlsr.l\t#{n - 8},{reg}")


emit("; GENERATED by tools/gen_sha256_asm.py - do not edit by hand.")
emit("; SHA-256 compression function for the 68000, fully unrolled.")
emit("")
emit("\tsection\ttext,code")
emit("\txdef\t_sha256_block")
emit("_sha256_block:")
emit("\tmovem.l\td2-d7/a2-a5,-(sp)")
emit("\tlea\t-256(sp),sp\t\t; W[64]")
emit("\tmove.l\ta0,a4\t\t\t; a4 = state")
emit("; message schedule")
emit("\tmove.l\tsp,a0")
for i in range(16):
    emit("\tmove.l\t(a1)+,(a0)+")
# W[i] = sigma1(W[i-2]) + W[i-7] + sigma0(W[i-15]) + W[i-16]
emit("\tmove.l\tsp,a0\t\t\t; a0 -> W[0]")
for i in range(16, 64):
    base = 4 * (i - 16)
    emit(f"; W[{i}]")
    emit(f"\tmove.l\t{4*(i-15)}(sp),d0\t\t; W[{i-15}]")
    emit("\tmove.l\td0,d1")
    emit("\tmove.l\td0,d2")
    rotr("d0", 7)
    rotr("d1", 18)
    emit("\teor.l\td1,d0")
    shr("d2", 3)
    emit("\teor.l\td2,d0\t\t\t; sigma0")
    emit(f"\tmove.l\t{4*(i-2)}(sp),d1\t\t; W[{i-2}]")
    emit("\tmove.l\td1,d2")
    emit("\tmove.l\td1,d3")
    rotr("d1", 17)
    rotr("d2", 19)
    emit("\teor.l\td2,d1")
    shr("d3", 10)
    emit("\teor.l\td3,d1\t\t\t; sigma1")
    emit("\tadd.l\td1,d0")
    emit(f"\tadd.l\t{4*(i-7)}(sp),d0\t\t; + W[{i-7}]")
    emit(f"\tadd.l\t{4*(i-16)}(sp),d0\t\t; + W[{i-16}]")
    emit(f"\tmove.l\td0,{4*i}(sp)")
emit("; load state: a..f -> d2..d7, g -> a2, h -> a3")
emit("\tmovem.l\t(a4),d2-d7/a2-a3")
emit("\tmove.l\tsp,a0\t\t\t; a0 -> W")
emit("\tlea\tsha256_k(pc),a1\t\t; a1 -> K")
for i in range(64):
    emit(f"; round {i}")
    # Sigma1(e) -> d0
    emit("\tmove.l\td6,d0")
    emit("\tmove.l\td6,d1")
    rotr("d0", 6)
    rotr("d1", 11)
    emit("\teor.l\td1,d0")
    emit("\tmove.l\td6,d1")
    rotr("d1", 25)
    emit("\teor.l\td1,d0\t\t\t; Sigma1(e)")
    emit("\tadd.l\ta3,d0\t\t\t; + h  (a3 is scratch from here on)")
    emit("\tadd.l\t(a1)+,d0\t\t; + K")
    emit("\tadd.l\t(a0)+,d0\t\t; + W")
    emit("\tmove.l\td0,a5\t\t\t; park the partial T1")
    # Ch(e,f,g) = g ^ (e & (f ^ g)) -> d1
    emit("\tmove.l\ta2,d0\t\t\t; g")
    emit("\tmove.l\td7,d1\t\t\t; f")
    emit("\teor.l\td0,d1")
    emit("\tand.l\td6,d1")
    emit("\teor.l\td0,d1\t\t\t; Ch")
    emit("\tadd.l\ta5,d1\t\t\t; T1")
    emit("\tmove.l\td1,a5\t\t\t; a5 = T1")
    # Sigma0(a) -> a3 (parked)
    emit("\tmove.l\td2,d0")
    emit("\tmove.l\td2,d1")
    rotr("d0", 2)
    rotr("d1", 13)
    emit("\teor.l\td1,d0")
    emit("\tmove.l\td2,d1")
    rotr("d1", 22)
    emit("\teor.l\td1,d0\t\t\t; Sigma0(a)")
    emit("\tmove.l\td0,a3")
    # Maj(a,b,c) = ((a ^ b) & (b ^ c)) ^ b -> d0, T2 = Sigma0 + Maj
    emit("\tmove.l\td3,d1")
    emit("\teor.l\td4,d1\t\t\t; b ^ c")
    emit("\tmove.l\td2,d0")
    emit("\teor.l\td3,d0\t\t\t; a ^ b")
    emit("\tand.l\td1,d0")
    emit("\teor.l\td3,d0\t\t\t; Maj")
    emit("\tadd.l\ta3,d0\t\t\t; T2")
    # rotate: h = g, g = f, f = e, e = d + T1, d = c, c = b, b = a, a = T1 + T2
    emit("\tmove.l\ta2,a3\t\t\t; h = g")
    emit("\tmove.l\td7,a2\t\t\t; g = f")
    emit("\tmove.l\td6,d7\t\t\t; f = e")
    emit("\tmove.l\td5,d6")
    emit("\tadd.l\ta5,d6\t\t\t; e = d + T1")
    emit("\tmove.l\td4,d5\t\t\t; d = c")
    emit("\tmove.l\td3,d4\t\t\t; c = b")
    emit("\tmove.l\td2,d3\t\t\t; b = a")
    emit("\tadd.l\ta5,d0")
    emit("\tmove.l\td0,d2\t\t\t; a = T1 + T2")
emit("; add into state")
emit("\tadd.l\td2,(a4)+")
emit("\tadd.l\td3,(a4)+")
emit("\tadd.l\td4,(a4)+")
emit("\tadd.l\td5,(a4)+")
emit("\tadd.l\td6,(a4)+")
emit("\tadd.l\td7,(a4)+")
emit("\tmove.l\ta2,d0")
emit("\tadd.l\td0,(a4)+")
emit("\tmove.l\ta3,d0")
emit("\tadd.l\td0,(a4)+")
emit("\tlea\t256(sp),sp")
emit("\tmovem.l\t(sp)+,d2-d7/a2-a5")
emit("\trts")
emit("")
emit("sha256_k:")
for i in range(0, 64, 4):
    emit("\tdc.l\t" + ",".join(f"${k:08x}" for k in K[i:i+4]))
sys.stdout.write("\n".join(out) + "\n")
