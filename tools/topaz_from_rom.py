#!/usr/bin/env python3
"""Extracts the Topaz 8 glyphs (characters 0x20..0xFF, 8x8) from a Kickstart 1.3 ROM for the host renderer
(ui/screen_host.c), so the host renderings of the client GUI show exactly what the Amiga shows. Writes a C header
with `font8_rom_glyphs[224][8]` to stdout. The ROM is the user's own copy (TOPAZ_ROM, default: the FS-UAE Kickstart
of tools/fsuae/a500-1mb-fast.fs-uae); the generated header lives in build/ and is not committed. Without a ROM a
plain placeholder font is emitted (every glyph a frame with the low code bits as dots), so make host-test still
runs and only the pictures look different - FONT8_ROM_SOURCE says which one you got."""
import os
import re
import struct
import sys

ROM = os.environ.get("TOPAZ_ROM", os.path.expanduser("~/Documents/FS-UAE/Kickstarts/kick13-34.5-a500.rom"))
BASES = (0xFC0000, 0xF80000)       # 256 KiB ROM at $FC0000 (1.3), 512 KiB at $F80000


def find_topaz8(rom):
    """TextFont: tf_YSize 8, tf_Style 0, tf_Flags ROMFONT|DESIGNED, tf_XSize 8, tf_Baseline 6 (NDK graphics/text.h)."""
    for m in re.finditer(rb"\x00\x08\x00[\x40\x41]\x00\x08\x00\x06", rom):
        off = m.start()
        ys, style, flags, xs, bl, smear, acc, lo, hi, cd, mod, cl, cs, ck = struct.unpack(">HBBHHHHBBIHIII", rom[off:off + 32])
        for base in BASES:
            if base <= cd < base + len(rom) and base <= cl < base + len(rom) and lo == 0x20 and hi == 0xFF and mod >= 192:
                return cd - base, mod, cl - base, lo, hi
    return None


def glyphs_from_rom(rom, cd, mod, cl, lo, hi):
    out = []
    for c in range(lo, hi + 1):
        bit, width = struct.unpack(">HH", rom[cl + (c - lo) * 4: cl + (c - lo) * 4 + 4])
        rows = []
        for r in range(8):
            row = rom[cd + r * mod: cd + (r + 1) * mod]
            v = int.from_bytes(row, "big")
            rows.append((v >> (mod * 8 - bit - 8)) & 0xFF if width else 0)
        out.append(rows)
    return out


def placeholder():
    out = []
    for c in range(0x20, 0x100):
        rows = [0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00]
        if c == 0x20:
            rows = [0] * 8
        else:
            for b in range(6):
                if c & (1 << b):
                    rows[1 + b] |= 0x18
        out.append(rows)
    return out


def main():
    src = "placeholder"
    glyphs = None
    if os.path.exists(ROM):
        rom = open(ROM, "rb").read()
        hit = find_topaz8(rom)
        if hit:
            glyphs = glyphs_from_rom(rom, *hit)
            src = "Kickstart ROM " + os.path.basename(ROM)
    if glyphs is None:
        glyphs = placeholder()
    print("/* generated by tools/topaz_from_rom.py - do not edit, do not commit (build/) */")
    print('#define FONT8_ROM_SOURCE "%s"' % src)
    print("static const unsigned char font8_rom_glyphs[224][8] = {")
    for i, rows in enumerate(glyphs):
        print("    {%s}, /* %s */" % (",".join("0x%02X" % r for r in rows), "0x%02X" % (0x20 + i)))
    print("};")


if __name__ == "__main__":
    main()
