#!/usr/bin/env python3
"""Generates proto/wabinary_tokens.h from the upstream WABinary token dictionaries.

Usage: gen_wab_tokens.py <whatsmeow binary/token/token.go> <Baileys src/WABinary/constants.ts> \
           <whatsmeow commit> <Baileys commit>  > proto/wabinary_tokens.h

Both tables must be identical (the script fails otherwise). Token numbering used by the C code:
0..235 = single-byte tokens (0 is the empty placeholder), 236 + dict * 256 + index = double-byte tokens.
"""
import json
import re
import sys

STR = re.compile(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\'')


def strings(text):
    return [json.loads('"%s"' % m.group(1)) if m.group(1) is not None else m.group(2) for m in STR.finditer(text)]


def between(text, start, end):
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)]


def go_tables(src):
    single = strings(between(src, "SingleByteTokens = [...]string{", "}"))
    body = between(src, "DoubleByteTokens = [...][]string{", "SingleByteTokens = [...]string{") \
        if src.index("DoubleByteTokens = [...][]string{") < src.index("SingleByteTokens = [...]string{") \
        else between(src, "DoubleByteTokens = [...][]string{", "// DictVersion")
    double = [strings(m) for m in re.findall(r'\{((?:\s*"(?:[^"\\]|\\.)*"\s*,?)+)\s*\}', body)]
    version = int(re.search(r"const DictVersion = (\d+)", src).group(1))
    return single, double, version


def ts_tables(src):
    single = strings(between(src, "export const SINGLE_BYTE_TOKENS = [", "export const TOKEN_MAP"))
    body = between(src, "export const DOUBLE_BYTE_TOKENS = [", "export const SINGLE_BYTE_TOKENS")
    quoted = r'(?:\'(?:[^\'\\]|\\.)*\'|"(?:[^"\\]|\\.)*")'
    double = [strings(m) for m in re.findall(r'\[((?:\s*%s\s*,?)+)\s*\]' % quoted, body)]
    return single, double


def main():
    go_path, ts_path, wm_commit, baileys_commit = sys.argv[1:5]
    single, double, version = go_tables(open(go_path, encoding="utf-8").read())
    ts_single, ts_double = ts_tables(open(ts_path, encoding="utf-8").read())
    assert single == ts_single, "single-byte tables differ"
    assert double == ts_double, "double-byte tables differ"
    assert len(single) == 236 and single[0] == "", "unexpected single-byte table size"
    assert len(double) == 4 and all(len(d) == 256 for d in double), "unexpected double-byte table size"

    tokens = single + [t for d in double for t in d]
    encoded = [t.encode("ascii") for t in tokens]
    assert len(set(encoded[1:])) == len(encoded) - 1 and all(encoded[1:]), "empty or duplicate token"
    offsets = [0]
    for t in encoded:
        offsets.append(offsets[-1] + len(t))
    assert offsets[-1] < 65536
    order = sorted(range(1, len(encoded)), key=lambda i: encoded[i])

    out = []
    out.append("/* Generated by tools/gen_wab_tokens.py - do not edit.")
    out.append(" * whatsmeow %s binary/token/token.go" % wm_commit)
    out.append(" * Baileys   %s src/WABinary/constants.ts (identical tables)" % baileys_commit)
    out.append(" * Included by proto/wabinary.c only. */")
    out.append("#define WAB_DICT_VERSION %d" % version)
    out.append("#define WAB_N_SINGLE %d" % len(single))
    out.append("#define WAB_N_TOKENS %d" % len(encoded))
    out.append("#define WAB_MAX_TOKEN_LEN %d" % max(map(len, encoded)))
    out.append("")
    out.append("/* all token strings back to back, without terminators */")
    out.append("static const uint8_t wab_tok_data[%d] = {" % offsets[-1])
    for i, t in enumerate(encoded):
        if not t:
            continue
        name = tokens[i].replace("*/", "* /").replace("/*", "/ *")
        where = "%d" % i if i < 236 else "d%d:%d" % ((i - 236) >> 8, (i - 236) & 255)
        out.append("    %s, /* %s %s */" % (",".join("%d" % b for b in t), where, name))
    out.append("};")

    def table(name, values):
        out.append("static const uint16_t %s[%d] = {" % (name, len(values)))
        for i in range(0, len(values), 12):
            out.append("    %s," % ", ".join("%d" % v for v in values[i:i + 12]))
        out.append("};")

    out.append("")
    out.append("/* token i = wab_tok_data[wab_tok_off[i] .. wab_tok_off[i + 1]) */")
    table("wab_tok_off", offsets)
    out.append("")
    out.append("/* token numbers 1.. sorted by their bytes, for the encoder's binary search */")
    table("wab_tok_sorted", order)
    print("\n".join(out))


main()
